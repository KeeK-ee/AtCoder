// n! が p で何回われるかを求める
ll Legendre(ll n, ll p) {
    ll res = 0;
    while (n) {
        res += n / p;
        n /= p;
    }
    return res;
}

/**
 * Kを素因数分解する
 * ->Kの各素因数の項p^eについてp^eを約数にもつN!のNのmaxが答え
 * 素因数を固定したとき, Nを求めるのはNを固定したとき, ルジャンドル(10!は2で何回割り切れるか?->10/2+10/4+10/8)
 */
void solve() {
    ll K; cin >> K;
    map<ll, ll> m;
    ll t=K;
    for(ll i=2; i*i<=K; i++){
        while(t%i==0){
            t/=i; m[i]++;
        }
    }
    if(t!=1) m[t]++;

    ll ans=1;
    for(auto [f, s] : m){
        ll l=1, r=INF;
        while(r-l>1){
            ll m=(l+r)/2;
            if(Legendre(m, f)<s) l=m;
            else r=m;
        }
        chmax(ans, r);
    }
    out(ans);
}

