/**
 * A以上B以下のうち~->f(B)-f(A-1)典型
 * CでもDでも割り切れない->全ての数-CまたはDで割り切れる数
 * CまたはDで割り切れる->包除原理
 * Cで割り切れる+Dで割り切れる-CかつDで割り切れる(CとDが互いに素でないときは特に注意　C*Dで割り切れるではなくLCM(C, D)で割り切れる)
 */
void solve() {
    ll A, B, C, D; cin >> A >> B >> C >> D;

    auto f = [&](ll x) -> ll {
        // 1以上x以下の整数のうちCでもDでも割り切れないものの個数
        ll res=x;
        res-=x/C;
        res-=x/D;
        res+=x/(lcm(C, D));
        return res;
    };

    ll ans=f(B)-f(A-1);
    out(ans);
}

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(nullptr);

    int t=1;
    // cin >> t;
    while (t--) solve();

    return 0;
}