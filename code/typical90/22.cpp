/**
 * 最終的に1辺rの立方体に分割する->このrが求められるか?(この視点がなかった)
 * r=a, b, cのgcdになる
 * 各辺に対して切断回数は{辺の長さ}/r-1回({辺の長さ}/rがその面の分割数)
 * 各辺に対しての上記のsumを取る
 */
void solve() {
// ロジックをちゃんと考える！！！
    ll a, b, c; cin >> a >> b >> c;
    ll g = gcd(a, gcd(b, c));
    ll ans = (a/g-1)+(b/g-1)+(c/g-1);
    out(ans);
}

