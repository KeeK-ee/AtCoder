int findSumOfDigits(int n) {
    int sum = 0;
    // nが負数の場合も考慮するなら abs(n) を使う
    // n = std::abs(n); 
    
    while (n > 0) { // n が 0 になるまで
        sum += n % 10; // 一番下の桁をsumに加える
        n /= 10;     // 一番下の桁を取り除く
    }
    return sum;
}

