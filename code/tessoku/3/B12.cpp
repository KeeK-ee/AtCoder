void solve() {
    ll N; cin >> N;
    double l=0, r=100, ans=0;
    while(l<r){
        double m = (l+r)/(double)2;
        double val = m*m*m+m;
        if(N-0.001<=val && val<=N+0.001){
            cout << fixed << setprecision(8);
            out(m);
            return;
        }
        else if(val>N)r=m;
        else l=m;
    }
}

